        sealed class Pen
        {
            public readonly List<Beat> Beats = new List<Beat>();
            string background = Bg.Scriptorium;
            string face = Face.Mira;

            public void Use(string nextBackground, string nextFace)
            {
                background = nextBackground;
                face = nextFace;
            }

            public void Narrate(string text, Choice[] choices)
            {
                Beat beat = Beat.Narration(text, background, face);
                beat.Choices = choices;
                Beats.Add(beat);
            }

            public void Narrate(string text)
            {
                Narrate(text, null);
            }

            public void Say(string speaker, string text, Choice[] choices)
            {
                string portrait = PortraitOf(speaker);
                Beats.Add(Beat.Say(speaker, text, portrait, background, choices));
                if (portrait != Face.None) face = portrait;
            }

            public void Say(string speaker, string text)
            {
                Say(speaker, text, null);
            }

            static string PortraitOf(string speaker)
            {
                switch (speaker)
                {
                    case "Мира": return Face.Mira;
                    case "Элеонора": return Face.Eleonora;
                    case "Себастьян": return Face.Sebastian;
                    case "Агата": return Face.Agatha;
                    case "Томас": return Face.Tomas;
                    default: return Face.None;
                }
            }
        }
